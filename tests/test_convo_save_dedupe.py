class _FakeCol:
    """Answers ``get(where={"chunk_hash": {"$in": [...]}})`` from fixed rows."""

    def __init__(self, metas):
        self.metas = metas

    def get(self, where=None, include=None, **_):
        wanted = set(where["chunk_hash"]["$in"])
        rows = [m for m in self.metas if m.get("chunk_hash") in wanted]
        return {"ids": [f"id{i}" for i in range(len(rows))], "metadatas": rows}


def _meta(text, index, **over):
    meta = {
        "chunk_hash": _sha(text),
        "chunk_index": index,
        "source_file": "/logs/a.jsonl",
        "wing": "w",
        "room": "r",
        "extract_mode": "exchange",
        "ingest_mode": "convos",
    }
    meta.update(over)
    return meta


def _prior(col, texts, base=10, skipped=frozenset()):
    return convo_miner._stored_prior_hashes(
        col, texts, "/logs/a.jsonl", "w", "r", "exchange", base, skipped
    )


def test_prior_counts_only_this_chats_stored_pieces_before_the_bookmark():
    col = _FakeCol(
        [
            _meta("mine", 2),
            _meta("other chat", 2, source_file="/logs/b.jsonl"),
            _meta("other wing", 2, wing="x"),
            _meta("other room", 2, room="q"),
            _meta("other mode", 2, extract_mode="general"),
            _meta("not convos", 2, ingest_mode="files"),
            _meta("after base", 10),
            _meta("listed skipped", 4),
            _meta("bool index", True),
        ]
    )
    texts = [
        "mine",
        "other chat",
        "other wing",
        "other room",
        "other mode",
        "not convos",
        "after base",
        "listed skipped",
        "bool index",
        "unseen",
    ]

    assert _prior(col, texts, skipped=frozenset({4})) == frozenset({_sha("mine")})


def test_a_new_piece_repeating_another_chat_is_still_stored():
    col = _FakeCol([_meta("shared text", 1, source_file="/logs/b.jsonl")])

    skip, _ = convo_miner.plan_skips(
        ["shared text"], prior=_prior(col, ["shared text"]), keep_one=False
    )

    assert skip == set()


