def test_a_bookmark_from_before_this_change_is_still_used(
    log, palace, tmp_path, capsys, monkeypatch
):
    monkeypatch.setenv("MEMPALACE_SAVE_DEDUPE", "0")
    _mine(log.path, palace)
    path = _bm(palace, log)
    bm = json.loads(path.read_text())
    bm.pop("skipped", None)
    path.write_text(json.dumps(bm))
    assert _bookmark_valid(bm)

    monkeypatch.delenv("MEMPALACE_SAVE_DEDUPE")
    log.grow(400, 1)
    say(log, STOP, STOP_ANSWER)
    log.grow(401, 2)
    capsys.readouterr()
    mine_convos(log.path, palace, wing=WING)
    assert "bookmark: read" in capsys.readouterr().out

    rows = _rows(palace)
    after = json.loads(path.read_text())
    new_stop = [i for i in range(bm["total"], after["total"]) if i not in rows]
    assert len(new_stop) == 1
    assert after["skipped"] == new_stop
    assert {3, 7} <= set(rows)


def _valid_bookmark(log, palace):
    _mine(log.path, palace)
    bm = json.loads(_bm(palace, log).read_text())
    assert _bookmark_valid(bm)
    return bm


@pytest.mark.parametrize(
    "skipped",
    [
        "3",
        [7, 3],
        [3, 3],
        [-1],
        "TOTAL",
        [True],
        [3.0],
        "ALL_BEFORE_BASE",
        None,
    ],
)
def test_a_malformed_skipped_list_is_no_bookmark(log, palace, skipped):
    bm = _valid_bookmark(log, palace)
    if skipped == "TOTAL":
        skipped = [bm["total"]]
    elif skipped == "ALL_BEFORE_BASE":
        skipped = list(range(bm["base"]))
    bm["skipped"] = skipped

    assert not _bookmark_valid(bm)


def test_an_all_boilerplate_chat_keeps_one_piece_and_gets_no_bookmark(tmp_path, palace):
    (tmp_path / "logs").mkdir()
    lg = Log(tmp_path / "logs" / "0a1b2c3d-boiler.jsonl")
    for i in range(12):
        say(lg, CAVEAT.replace("Caveat", f"Caveat {i}") + " " + "x" * 300, "ok " * 40)

    _mine(lg.path, palace)

    rows = _rows(palace)
    assert sorted(rows) == [0]
    assert rows[0][1]["chunk_skipped"] == rows[0][1]["chunk_total"] - 1
    assert not _bm(palace, lg).exists()
    assert file_already_mined(_col(palace), lg.path, check_mtime=True, extract_mode="exchange")


def _seed_rows(palace, chunk_total, stored, chunk_skipped, mtime):
    from mempalace.palace import get_collection

    col = get_collection(palace)
    metas = []
    for i in stored:
        meta = {
            "source_file": "/chats/a.jsonl",
            "wing": WING,
            "room": "general",
            "chunk_index": i,
            "ingest_mode": "convos",
            "extract_mode": "exchange",
            "normalize_version": convo_miner.NORMALIZE_VERSION,
            "chunk_total": chunk_total,
            "source_mtime": mtime,
        }
        if chunk_skipped is not None:
            meta["chunk_skipped"] = chunk_skipped
        metas.append(meta)
    col.upsert(
        ids=[f"d{i}" for i in stored],
        documents=[f"piece {i}" for i in stored],
        metadatas=metas,
    )
    return col


def test_stored_plus_skipped_counts_as_saved(palace):
    col = _seed_rows(palace, chunk_total=5, stored=[0, 1, 3], chunk_skipped=2, mtime=1.0)

    assert "/chats/a.jsonl" in prefetch_mined_set(col, extract_mode="exchange")


@pytest.mark.parametrize("bad", [None, 1, -1, 5, 9, "2", True, 2.5])
def test_a_wrong_or_malformed_skip_count_never_counts_as_saved(palace, bad):
    col = _seed_rows(palace, chunk_total=5, stored=[0, 1, 3], chunk_skipped=bad, mtime=1.0)

    assert "/chats/a.jsonl" not in prefetch_mined_set(col, extract_mode="exchange")


@pytest.mark.parametrize("bad", [None, 1, -1, 5, "2", True, 2.5])
def test_file_already_mined_needs_stored_plus_skipped(palace, tmp_path, bad):
    source = tmp_path / "a.jsonl"
    source.write_text("x")
    mtime = os.path.getmtime(source)
    from mempalace.palace import get_collection

    col = get_collection(palace)
    for skipped, expect in ((2, True), (bad, False)):
        col.delete(where={"source_file": str(source)}) if col.count() else None
        metas = [
            {
                "source_file": str(source),
                "chunk_index": i,
                "ingest_mode": "convos",
                "extract_mode": "exchange",
                "normalize_version": convo_miner.NORMALIZE_VERSION,
                "chunk_total": 5,
                "source_mtime": mtime,
                **({"chunk_skipped": skipped} if skipped is not None else {}),
            }
            for i in (0, 1, 3)
        ]
        col.upsert(ids=["a0", "a1", "a3"], documents=["p0", "p1", "p3"], metadatas=metas)
        assert (
            file_already_mined(col, str(source), check_mtime=True, extract_mode="exchange")
            is expect
        ), skipped


