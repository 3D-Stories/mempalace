def _seed_pairs(palace, source, mtime, pairs):
    from mempalace.palace import get_collection

    col = get_collection(palace)
    ids, docs, metas = [], [], []
    for n, (index, total, skipped) in enumerate(pairs):
        meta = {
            "source_file": source,
            "chunk_index": index,
            "ingest_mode": "convos",
            "extract_mode": "exchange",
            "normalize_version": convo_miner.NORMALIZE_VERSION,
            "chunk_total": total,
            "source_mtime": mtime,
        }
        if skipped is not None:
            meta["chunk_skipped"] = skipped
        ids.append(f"r{n}")
        docs.append(f"piece {index}")
        metas.append(meta)
    col.upsert(ids=ids, documents=docs, metadatas=metas)
    return col


