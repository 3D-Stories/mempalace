CAVEAT = (
    "<local-command-caveat>Caveat: the messages below were generated by the user "
    "while running local commands.</local-command-caveat>"
)
STOP = "Stop hook feedback: run the gate again"
STOP_ANSWER = "Running the gate again now."


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def say(log, user, answer):
    log._write({"type": "user", "message": {"role": "user", "content": user}})
    log._write(
        {
            "type": "assistant",
            "message": {"role": "assistant", "content": [{"type": "text", "text": answer}]},
        }
    )


def _rows(palace):
    col = chromadb.PersistentClient(path=palace).get_collection("mempalace_drawers")
    got = col.get(include=["documents", "metadatas"])
    return {
        m["chunk_index"]: (doc, m)
        for doc, m in zip(got["documents"], got["metadatas"])
        if m.get("ingest_mode") == "convos"
    }


def _col(palace):
    return chromadb.PersistentClient(path=palace).get_collection("mempalace_drawers")


