class _PagedRows:
    """Row labels paged by ``limit`` and ``offset``, as chromadb pages them."""

    def __init__(self, metas):
        self.metas = metas
        self.offsets = []

    def count(self):
        return len(self.metas)

    def get(self, *, limit=None, offset=None, include=None, **_):
        self.offsets.append(offset)
        part = self.metas[offset : offset + limit]
        return {"ids": [f"d{offset + i}" for i in range(len(part))], "metadatas": part}


