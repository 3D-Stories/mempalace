class _FakeCol:
    """Answers the prior lookup from fixed ``(drawer_id, document, meta)`` rows: a
    ``where`` of equality and ``$in`` clauses (labels), or ``ids`` (with text)."""

    def __init__(self, rows):
        self.rows = rows

    def get(self, where=None, ids=None, include=None, **_):
        if ids is not None:
            picked = [r for r in self.rows if r[0] in set(ids)]
        else:
            picked = list(self.rows)
            for clause in where.get("$and", [where]):
                ((key, cond),) = clause.items()
                if isinstance(cond, dict):
                    picked = [r for r in picked if r[2].get(key) in set(cond["$in"])]
                else:
                    picked = [r for r in picked if r[2].get(key) == cond]
        return {
            "ids": [r[0] for r in picked],
            "documents": [r[1] for r in picked],
            "metadatas": [r[2] for r in picked],
        }


def _meta(text, index, *, document=None, drawer_id=None, **over):
    meta = {
        "chunk_hash": _sha(text),
        "chunk_index": index,
        "source_file": "/logs/a.jsonl",
        "wing": "w",
        "room": "r",
        "extract_mode": "exchange",
        "ingest_mode": "convos",
    }
    meta.update(over)
    if drawer_id is None:
        drawer_id = convo_miner.make_convo_drawer_id(
            meta["wing"], meta["room"], meta["source_file"], meta["extract_mode"], index
        )
    return (drawer_id, text if document is None else document, meta)


