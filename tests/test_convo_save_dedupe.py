"""Save-time skip in chat saves (3D-Stories fork, sysop#297).

A full read and a bookmark save store neither boilerplate nor a repeat of an
earlier piece of the same chat, keep the piece numbers, and still agree with each
other exactly. The "fully saved?" checks count stored + skipped.
"""

