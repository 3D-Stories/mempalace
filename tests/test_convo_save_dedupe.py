def _seed_rows(palace, chunk_total, stored, chunk_skipped, mtime):
    from mempalace.palace import get_collection

    col = get_collection(palace)
    metas = []
    for i in stored:
        meta = {
            "source_file": "/chats/a.jsonl",
            "wing": WING,
            "room": "general",
            "chunk_index": i,
            "ingest_mode": "convos",
            "extract_mode": "exchange",
            "normalize_version": convo_miner.NORMALIZE_VERSION,
            "chunk_total": chunk_total,
            "source_mtime": mtime,
        }
        if chunk_skipped is not None:
            meta["chunk_skipped"] = chunk_skipped
        metas.append(meta)
    col.upsert(
        ids=[f"d{i}" for i in stored],
        documents=[f"piece {i}" for i in stored],
        metadatas=metas,
    )
    return col


