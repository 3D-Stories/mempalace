class _LimitedCol(_FakeCol):
    """The prior lookup's fake, also honouring ``limit``; records each ``limit`` asked."""

    def __init__(self, rows):
        super().__init__(rows)
        self.limits = []

    def get(self, where=None, ids=None, include=None, limit=None, **_):
        got = super().get(where=where, ids=ids, include=include)
        if ids is None:
            self.limits.append(limit)
            if limit is not None:
                got = {key: value[:limit] for key, value in got.items()}
        return got


