def _grow_capped_tail(log):
    """Piece 14 repeats stored piece 4, 15 is boilerplate, 16 is new."""
    say(log, STOP, STOP_ANSWER)
    say(log, CAVEAT, "ok")
    say(log, "Question 700, never asked before?", "A fresh answer 700.")


def _assert_capped_save(palace, log):
    rows = _rows(palace)
    bm = json.loads(_bm(palace, log).read_text())
    assert bm["total"] == 17, bm
    assert any("Question 700" in doc for doc, _m in rows.values()), "the new piece was not saved"
    # The cap only drops the same-chat repeat skip: the repeat is stored, the
    # boilerplate is still skipped, and the counts still add up.
    assert 14 in rows and 16 in rows
    assert bm["skipped"] == [3, 7, 15]
    assert set(bm["skipped"]) == set(range(bm["total"])) - set(rows)
    # The bulk check the sweep uses still counts the chat as saved. (The per-file
    # mtime check reads False after any bookmark save, on the release code too.)
    assert log.path in prefetch_mined_set(_col(palace), extract_mode="exchange")


def test_a_capped_prior_lookup_still_saves_the_new_pieces(log, palace, capsys, monkeypatch):
    mine_convos(log.path, palace, wing=WING)
    monkeypatch.setattr(convo_miner, "_PRIOR_ROW_CAP", 0, raising=False)
