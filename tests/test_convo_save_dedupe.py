def test_a_listed_text_is_skipped(log, palace, tmp_path):
    rows = _rows_after_full(log, palace)
    listed_doc = rows[1][0]
    cfg = tmp_path / "cfg"
    cfg.mkdir(exist_ok=True)
    (cfg / "boilerplate.json").write_text(
        json.dumps({"version": 1, "sha256": [_sha(listed_doc)]}), encoding="utf-8"
    )
    other = str(tmp_path / "palace_listed")

    _full_mine(log.path, other)

    assert 1 not in _rows(other)


def _rows_after_full(log, palace):
    _full_mine(log.path, palace)
    return _rows(palace)


@pytest.mark.parametrize("label_path", [True, False], ids=["label-path", "and-path"])
def test_bookmark_save_matches_a_full_read_with_skips(
    log, palace, tmp_path, capsys, monkeypatch, label_path
):
    if not label_path:
        monkeypatch.setattr(convo_miner, "_INVENTORY_LABEL_FETCH_MAX", 0)
    _mine(log.path, palace)
    assert _bm(palace, log).exists()

    say(log, STOP, STOP_ANSWER)
    log.grow(200, 1)
    say(log, CAVEAT, "ok")
    log.grow(201, 2)
    say(log, "Question 201 again?", "Same answer.")
    say(log, "Question 201 again?", "Same answer.")
    log.grow(203, 2)
    capsys.readouterr()
    _mine(log.path, palace)
    out = capsys.readouterr().out
    assert "bookmark: read" in out, out

    _assert_same(palace, tmp_path, log.path)
    rows = _rows(palace)
    stored = set(rows)
    bm = json.loads(_bm(palace, log).read_text())
    assert set(bm["skipped"]) == set(range(bm["total"])) - stored
    # 3, 7 from the first save; 14 the stop message again, 16 boilerplate, 20 the
    # repeated question.
    assert bm["skipped"] == [3, 7, 14, 16, 20]
    # Every row carries the (chunk_total, chunk_skipped) pair of ONE save: the
    # first save's (14, 2) before the bookmark, this save's (total, 5) from it
    # on. A mixed pair would let a short save read as complete.
    base = bm["base"]
    # Pieces 0-13 existed at the first save (13 was its bookmark point and is
    # unchanged, so this save leaves its row alone); 14 on are new.
    first_save = {i: rows[i][1] for i in stored if i < 14}
    this_save = {i: rows[i][1] for i in stored if i >= 14}
    assert this_save
    for meta in this_save.values():
        assert (meta["chunk_total"], meta.get("chunk_skipped")) == (bm["total"], 5)
    for i, meta in first_save.items():
        assert (meta["chunk_total"], meta.get("chunk_skipped")) == (14, 2), i
    assert base > 13


def test_the_anchor_moves_to_the_last_stored_piece(log, palace, tmp_path, capsys):
    say(log, STOP, STOP_ANSWER)
    log.grow(300, 1)
    _mine(log.path, palace)

    bm = json.loads(_bm(palace, log).read_text())
    base = bm["base"]
    assert base - 1 in bm["skipped"]
    anchor = max(i for i in range(base) if i not in bm["skipped"])
    assert bm["prev_hash"] == _sha(_rows(palace)[anchor][0])

    log.grow(301, 3)
    capsys.readouterr()
    _mine(log.path, palace)
    assert "bookmark: read" in capsys.readouterr().out
    _assert_same(palace, tmp_path, log.path)


def test_a_bookmark_save_anchors_on_the_last_stored_piece(log, palace, tmp_path, capsys):
    _mine(log.path, palace)
    say(log, STOP, STOP_ANSWER)  # piece 14 repeats piece 4
    say(log, "Final question?", "Final answer.")  # piece 15, the new bookmark base
    capsys.readouterr()
    _mine(log.path, palace)
    assert "bookmark: read" in capsys.readouterr().out

    bm = json.loads(_bm(palace, log).read_text())
    assert bm["base"] == 15
    assert 14 in bm["skipped"]
    assert bm["prev_hash"] == _sha(_rows(palace)[13][0])

    log.grow(400, 2)
    capsys.readouterr()
    _mine(log.path, palace)
    assert "bookmark: read" in capsys.readouterr().out
    _assert_same(palace, tmp_path, log.path)


def test_a_bookmark_save_deletes_a_stored_piece_it_now_skips(palace, tmp_path, capsys, monkeypatch):
    (tmp_path / "logs").mkdir()
    lg = Log(tmp_path / "logs" / "0a1b2c3d-repeat-last.jsonl")
    lg.grow(0, 6)
    say(lg, STOP, STOP_ANSWER)  # piece 6
    lg.grow(6, 6)
    say(lg, STOP, STOP_ANSWER)  # piece 13 repeats piece 6, and is the bookmark base
    monkeypatch.setenv("MEMPALACE_SAVE_DEDUPE", "0")
    _mine(lg.path, palace)  # a save from before the skip: every piece stored
    monkeypatch.delenv("MEMPALACE_SAVE_DEDUPE")
    assert 13 in _rows(palace)
    assert json.loads(_bm(palace, lg).read_text())["base"] == 13

    lg.grow(100, 2)
    capsys.readouterr()
    _mine(lg.path, palace)
    assert "bookmark: read" in capsys.readouterr().out

    assert 13 not in _rows(palace)
    assert json.loads(_bm(palace, lg).read_text())["skipped"] == [13]
    _assert_same(palace, tmp_path, lg.path)


