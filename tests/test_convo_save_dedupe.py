def test_full_read_skips_boilerplate_and_later_repeats(log, palace):
    _full_mine(log.path, palace)

    rows = _rows(palace)
    assert sorted(rows) == [0, 1, 2, 4, 5, 6, 8, 9, 10, 11, 12, 13]
    assert rows[4][0].startswith("> " + STOP)
    assert all(m["chunk_total"] == 14 and m["chunk_skipped"] == 2 for _, m in rows.values())


def test_full_read_counts_the_chat_as_saved(log, palace):
    _full_mine(log.path, palace)
    col = _col(palace)

    assert file_already_mined(col, log.path, check_mtime=True, extract_mode="exchange")
    assert log.path in prefetch_mined_set(col, extract_mode="exchange")


def test_full_read_deletes_rows_of_pieces_it_now_skips(log, palace, monkeypatch):
    monkeypatch.setenv("MEMPALACE_SAVE_DEDUPE", "0")
    _full_mine(log.path, palace)
    assert sorted(_rows(palace)) == list(range(14))
    assert all("chunk_skipped" not in m for _, m in _rows(palace).values())

    monkeypatch.delenv("MEMPALACE_SAVE_DEDUPE")
    st = os.stat(log.path)
    os.utime(log.path, (st.st_atime, st.st_mtime + 5))
    _full_mine(log.path, palace)

    rows = _rows(palace)
    assert sorted(rows) == [0, 1, 2, 4, 5, 6, 8, 9, 10, 11, 12, 13]
    assert all(m["chunk_skipped"] == 2 for _, m in rows.values())


